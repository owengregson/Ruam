import { describe, expect, test } from "bun:test";
import { createHash } from "node:crypto";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { runArtifactTests } from "../../src/algorithm-state/qualification/artifact-tests.js";

function fixture() {
	const root = mkdtempSync(join(tmpdir(), "ruam-artifact-tests-"));
	const projectRoot = join(root, "application");
	mkdirSync(projectRoot);
	const source = join(projectRoot, "operation.ts"), artifact = join(root, "generated.js");
	writeFileSync(source, "export const value = 1;");
	writeFileSync(artifact, "export const value = 42;");
	writeFileSync(join(projectRoot, "operation.test.ts"), `import { expect, test } from "bun:test";\nimport { value } from "./operation.ts";\ntest("generated bytes", async () => { expect(value).toBe(42); const fresh = await import("./operation.ts?fresh=1"); expect(fresh.value).toBe(42); });`);
	const sha256 = createHash("sha256").update(readFileSync(artifact)).digest("hex");
	return { root, projectRoot, source, artifact, sha256 };
}

describe("exact artifact application tests", () => {
	test("executes generated bytes through a real test import and requires load evidence", () => {
		const f = fixture();
		try {
			const report = runArtifactTests({ ...f, outputDirectory: join(f.root, "result"), substitutions: [f], tests: ["operation.test.ts"], timeoutMs: 10_000 });
			if (report.status !== "pass") console.error(report, readFileSync(join(f.root, "result/0.stderr.log"), "utf8"));
			expect(report.status).toBe("pass");
			expect(report.results[0]!.loadedArtifacts[0]!.sha256).toBe(f.sha256);
			expect(report.results[0]!.loadedArtifacts.some(load => load.importPath.endsWith("?fresh=1"))).toBe(true);
			expect(report.boundFilesUnchanged).toBe(true);
			expect(report.protectionQualified).toBe(false);
			expect(report.releaseApproved).toBe(false);
			writeFileSync(join(f.projectRoot, "unrelated.test.ts"), `import { expect, test } from "bun:test"; test("unrelated", () => expect(1).toBe(1));`);
			const untouched = runArtifactTests({ ...f, outputDirectory: join(f.root, "untouched"), substitutions: [f], tests: ["unrelated.test.ts"], timeoutMs: 10_000 });
			expect(untouched.results[0]!.exitCode).toBe(0);
			expect(untouched.status).toBe("fail");
			expect(untouched.missingSubstitutions).toHaveLength(1);
		} finally { rmSync(f.root, { recursive: true, force: true }); }
	});

	test("an import followed only by skipped tests cannot pass qualification", () => {
		const f = fixture();
		try {
			writeFileSync(join(f.projectRoot, "skipped.test.ts"), `import { expect, test } from "bun:test"; import { value } from "./operation.ts"; console.log(value); test.skip("unchecked", () => expect(value).toBe(-100));`);
			const report = runArtifactTests({ ...f, outputDirectory: join(f.root, "skipped"), substitutions: [f], tests: ["skipped.test.ts"], timeoutMs: 10_000 });
			expect(report.results[0]!.exitCode).toBe(0);
			expect(report.results[0]!.loadedArtifacts.length).toBeGreaterThan(0);
			expect(report.results[0]!.counts?.executed).toBe(0);
			expect(report.status).toBe("fail");
		} finally { rmSync(f.root, { recursive: true, force: true }); }
	});

	test("terminates a hung generated module without awarding test credit", () => {
		const f = fixture();
		try {
			writeFileSync(f.artifact, "while (true) {} export const value = 42;");
			const sha256 = createHash("sha256").update(readFileSync(f.artifact)).digest("hex");
			const report = runArtifactTests({ ...f, outputDirectory: join(f.root, "hung"), substitutions: [{ ...f, sha256 }], tests: ["operation.test.ts"], timeoutMs: 500 });
			expect(report.status).toBe("fail");
			expect(report.results[0]!.signal).toBe("SIGKILL");
			expect(report.results[0]!.error).not.toBeNull();
		} finally { rmSync(f.root, { recursive: true, force: true }); }
	});

	test("rejects stale artifacts and destructive output locations before running tests", () => {
		const f = fixture();
		try {
			const options = { ...f, outputDirectory: join(f.root, "result"), substitutions: [f], tests: ["operation.test.ts"] };
			expect(() => runArtifactTests({ ...options, outputDirectory: join(f.projectRoot, "generated") })).toThrow("outside the application tree");
			expect(() => runArtifactTests({ ...options, outputDirectory: f.root })).toThrow("new directory");
			writeFileSync(f.artifact, "export const value = 1;");
			expect(() => runArtifactTests(options)).toThrow("Artifact hash does not match");
		} finally { rmSync(f.root, { recursive: true, force: true }); }
	});
});
